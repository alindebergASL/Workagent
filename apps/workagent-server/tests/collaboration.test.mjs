const token = 'synthetic-owner-credential-at-least-32-characters';
const peerToken = 'synthetic-peer-credential-at-least-32-characters';
const accounts = [{ id: 'peer', name: 'Synthetic Peer', token: peerToken }];
const origin = 'https://synthetic.example.test';
function fixture() {
  let state = initialState('owner');
  const store = { read: async fn => structuredClone(await fn(structuredClone(state))), transaction: async fn => { const next = structuredClone(state); const result = await fn(next); state = next; return structuredClone(result); } };
  const workspace = new Workspace(store, { peers: accounts });
  return { workspace, store };
}
const saveInput = (w, commandId, value) => { const book = structuredClone(w.book); book.sheets.sheet1.cellData = { 0: { 0: { v: value, t: 2 } } }; return { commandId, book, contentRevision: w.contentRevision, permissionRevision: w.expected.permissionRevision, accessRevision: w.access.revision }; };
const denied = action => assert.rejects(action, e => e.status === 403);
test('credentials bind distinct actors; old owner cookies survive; claims cannot impersonate; peer removal invalidates session', () => {
  const auth = identity({ token, owner: 'owner', origin, accounts });
  const cookie = auth.login(peerToken);
  assert.equal(auth.authenticate({ headers: { cookie: `workagent_session=${cookie}`, 'x-user': 'owner' } }), 'peer');
  assert.equal(auth.authenticate({ headers: { authorization: `Bearer ${peerToken}` } }), 'peer');
  assert.throws(() => identity({ token, owner: 'owner', origin }).authenticate({ headers: { cookie: `workagent_session=${cookie}` } }), /access_denied/);
  const expiry = String(Date.now() + 100000), signature = createHmac('sha256', token).update(expiry).digest('base64url');
  assert.equal(auth.authenticate({ headers: { cookie: `workagent_session=${expiry}.${signature}` } }), 'owner');
  assert.throws(() => auth.authenticate({ headers: { cookie: `workagent_session=${cookie}.extra` } }), /access_denied/);
  assert.throws(() => identity({ token, owner: 'owner', origin, accounts: [{ id: 'owner', token: peerToken }] }));
});
test('grant/read/edit/revoke/reconnect, actor dedup, stale saves, human protection and no source/global leaks', async () => {
  const { workspace: w, store } = fixture();
  const a = await w.createBlank('owner', { commandId: 'a', title: 'Shared' });
  const b = await w.createBlank('owner', { commandId: 'b', title: 'Secret unrelated work' });
  await store.transaction(s => { s.works[a.workId].sourceIds = ['secret-source']; s.works[a.workId].messages.push({ text: 'private source context' }); s.works[a.workId].original = { id: 'private-file' }; });
  assert.deepEqual(await w.list('peer'), []); await denied(w.get('peer', a.workId));
  await denied(w.share('peer', a.workId, { commandId: 'bad', peer: 'peer', role: 'editor', accessRevision: 0 }));
  await w.share('owner', a.workId, { commandId: 'read', peer: 'peer', role: 'read', accessRevision: 0 });
  let peer = await w.get('peer', a.workId);
  assert.equal(peer.access.role, 'read'); assert.equal(peer.sourceIds, undefined); assert.equal(peer.original, undefined); assert.deepEqual(peer.messages, []);
  await denied(w.save('peer', a.workId, saveInput(peer, 'no-write', 3)));
  await w.share('owner', a.workId, { commandId: 'edit', peer: 'peer', role: 'editor', accessRevision: 1 });
  peer = await w.get('peer', a.workId); const owner = await w.get('owner', a.workId);
  const ownerDraft = saveInput(owner, 'same-command', 11), peerDraft = saveInput(peer, 'same-command', 22);
  await w.save('owner', a.workId, ownerDraft);
  await assert.rejects(w.save('peer', a.workId, peerDraft), /save_conflict/);
  assert.equal(ownerDraft.book.sheets.sheet1.cellData[0][0].v, 11); assert.equal(peerDraft.book.sheets.sheet1.cellData[0][0].v, 22);
  peer = await w.get('peer', a.workId); const accepted = saveInput(peer, 'same-command', 22);
  assert.equal((await w.save('peer', a.workId, accepted)).contentRevision, 3);
  assert.equal((await w.save('peer', a.workId, accepted)).contentRevision, 3);
  const after = await w.get('owner', a.workId); assert.ok(after.humanCells.includes('sheet1:0:0'));
  const result = await w.mutate('owner', a.workId, { commandId: 'agent', expected: after.expected, patch: { cells: [{ sheetId: 'sheet1', row: 0, column: 0, value: 99 }] } });
  assert.equal(result.status, 'proposed');
  await denied(w.command('peer', { commandId: 'paid', kind: 'continue', workId: a.workId, expectedIntentRevision: 0, sourceIds: [], text: 'spend' }));
  await denied(w.command('peer', { commandId: 'stop', kind: 'cancel', workId: a.workId, sourceIds: [] }));
  await denied(w.decide('peer', a.workId, result.proposalId, { commandId: 'accept', decision: 'accept', expected: after.expected }));
  await denied(w.source('peer', { commandId: 'source', name: 'source', content: 'x', synthetic: true }));
  const batch = await w.events('peer', 0); assert.equal(batch.kind, 'reset'); assert.equal(batch.cursor, 0);
  assert.deepEqual(batch.works.map(x => x.id), [a.workId]); assert.ok(!JSON.stringify(batch).includes(b.workId)); assert.ok(!JSON.stringify(batch).includes('secret-source'));
  await w.share('owner', a.workId, { commandId: 'revoke', peer: 'peer', role: null, accessRevision: 2 });
  await denied(w.get('peer', a.workId)); await denied(w.save('peer', a.workId, accepted));
  assert.deepEqual((await w.events('peer', 0)).snapshots, []);
  await w.share('owner', a.workId, { commandId: 'regrant', peer: 'peer', role: 'editor', accessRevision: 3 });
  await assert.rejects(w.save('peer', a.workId, accepted), /access_changed/);
  assert.equal((await store.read(s => Object.values(s.jobs))).length, 0);
  assert.equal((await w.get('owner', a.workId)).proposals.length, 1);
});
test('real HTTP handler binds sessions and rechecks sharing across reads, saves, events and privileged routes', async () => {
  const { workspace } = fixture(); let effects = 0;
  const exchange = new CsvExchange({ workspace, files: { read() { effects++; throw new Error('unexpected file read'); } } }), maintenance = new Maintenance({ workspace });
  const handler = createHandler({ workspace, exchange, maintenance, owner: 'owner', token, origin, accounts, clientRoot: '/tmp', accounting: { status() { effects++; return { secret: true }; } }, onCommand() { effects++; } });
  async function request(path, input, cookie, extra = {}) {
    const req = Readable.from(input === undefined ? [] : [Buffer.from(JSON.stringify(input))]); Object.assign(req, { url: path, method: input === undefined ? 'GET' : 'POST', headers: { origin, 'content-type': 'application/json', cookie, ...extra } });
    const headers = {}; let status, value;
    await handler(req, { setHeader(k,v) { headers[k] = v; }, writeHead(s) { status = s; }, end(v) { value = JSON.parse(v); } });
    return { status, value, cookie: headers['Set-Cookie']?.split(';')[0] };
  }
  const owner = (await request('/api/session', { token })).cookie;
  const peer = (await request('/api/session', { token: peerToken, principal: 'owner' })).cookie;
  assert.equal((await request('/api/session', undefined, peer)).value.principal, 'peer');
  const created = await request('/api/work/blank', { commandId: 'blank', title: 'Shared' }, owner), workId = created.value.workId;
  assert.equal((await request(`/api/work/${workId}?principal=owner`, undefined, peer, { 'x-user': 'owner' })).status, 403);
  assert.equal((await request(`/api/work/${workId}/sharing`, { commandId: 'grant', peer: 'peer', role: 'editor', accessRevision: 0 }, owner)).status, 200);
  const shared = (await request(`/api/work/${workId}`, undefined, peer)).value, input = saveInput(shared, 'save', 7);
  assert.equal((await request(`/api/work/${workId}/save`, input, peer)).status, 200);
  assert.equal((await request('/api/accounting', undefined, peer)).status, 403);
  assert.equal((await request('/api/owned-sources', undefined, peer)).status, 403);
  assert.equal((await request(`/api/work/${workId}/original/private-file`, undefined, peer)).status, 403);
  assert.equal((await request(`/api/work/${workId}/sharing`, undefined, peer)).status, 403);
  assert.equal((await request('/api/work/blank', { commandId: 'peer-blank', title: 'Forbidden' }, peer)).status, 403);
  const ownerProfile = (await request('/api/session', undefined, owner)).value;
  assert.equal((await request(`/api/work/${workId}`, undefined, peer, { 'x-workagent-session-binding': ownerProfile.binding })).status, 403);
  assert.equal((await request('/api/work/commands', { commandId: 'paid', kind: 'start', text: 'spend', sourceIds: [] }, peer)).status, 403);
  assert.equal((await request(`/api/work/${workId}/sharing`, { commandId: 'revoke', peer: 'peer', role: null, accessRevision: 1 }, owner)).status, 200);
  assert.equal((await request(`/api/work/${workId}/save`, input, peer)).status, 403);
  assert.equal((await request(`/api/work/${workId}`, undefined, peer)).status, 403);
  assert.deepEqual((await request('/api/events?after=0', undefined, peer)).value.snapshots, []);
  assert.equal(effects, 0);
});

test('document shares persist across Workspace restart; defaults and removed configured peers cannot use retained grants', async () => {
  const { workspace: w, store } = fixture();
  const { workId } = await w.createBlank('owner', { commandId: 'doc', kind: 'document', title: 'Shared document' });
  await assert.rejects(w.share('owner', workId, { commandId: 'unknown', peer: 'stranger', role: 'editor', accessRevision: 0 }), /peer_not_configured/);
  await w.share('owner', workId, { commandId: 'grant-doc', peer: 'peer', role: 'editor', accessRevision: 0 });
  const restarted = new Workspace(store, { peers: accounts });
  const peer = await restarted.get('peer', workId), document = blankDocument(workId, peer.document.title, 'Peer-authored paragraph');
  const input = { commandId: 'doc-save', document, contentRevision: peer.contentRevision, permissionRevision: peer.expected.permissionRevision, accessRevision: peer.access.revision };
  await restarted.save('peer', workId, input);
  const current = await restarted.get('owner', workId); assert.equal(current.humanDocument, true); assert.equal(current.lastHumanActor, 'peer');
  assert.equal((await restarted.get('peer', workId)).document.body.dataStream, document.body.dataStream);
  const defaults = new Workspace(store);
  await denied(defaults.get('peer', workId)); await denied(defaults.events('peer', 0)); await denied(defaults.save('peer', workId, input));
  await store.transaction(s => { s.enabled = false; s.permissionRevision++; });
  await denied(restarted.save('peer', workId, input)); await denied(restarted.get('owner', workId));
});
